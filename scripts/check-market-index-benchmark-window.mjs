import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import ts from "typescript";
import vm from "node:vm";
const source = readFileSync(new URL("../app/lib/research/marketIndexBenchmarkWindow.ts", import.meta.url), "utf8");
const js = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
const module = { exports: {} };
vm.runInNewContext(js, { module, exports: module.exports, Date, Intl, Number, String });
const check = module.exports.assessBenchmarkWindow;
const base = { index: "nikkei", value: 64000, source: "test", capturedAt: "2026-10-21T00:06:00Z" };
assert.equal(check("intraday_0905", { ...base, observedAt: "2026-10-21T00:05:00Z" }).status, "intraday_observed");
assert.equal(check("intraday_0905", { ...base, observedAt: null }).status, "missing");
assert.equal(check("intraday_0905", { ...base, observedAt: "2026-10-21T00:08:00Z" }).status, "future_timestamp");
assert.equal(check("intraday_0905", { ...base, observedAt: "2026-10-21T00:00:00Z" }).status, "intraday_observed");
assert.equal(check("intraday_0905", { ...base, observedAt: "2026-10-21T00:06:00Z" }).status, "outside_window");
assert.equal(check("intraday_0905", { ...base, observedAt: "2026-10-20T00:05:00Z" }).status, "stale");
assert.equal(check("daily_close", { ...base, observedAt: null, sessionDateJst: "2026-10-21" }).status, "daily_observed");
assert.equal(check("daily_close", { ...base, observedAt: null }).status, "missing");
assert.equal(check("daily_close", { ...base, observedAt: null, sessionDateJst: "2026-10-22" }).status, "future_timestamp");
console.log("PASS: 9 market-index benchmark window checks");
