import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import ts from "typescript";
import vm from "node:vm";
const src = readFileSync(new URL("../app/lib/research/marketRelativeMatchedStudy.ts", import.meta.url), "utf8");
const js = ts.transpileModule(src, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
const module = { exports: {} };
vm.runInNewContext(js, { module, exports: module.exports, Number, String, Map, Set, Math });
const summarize = module.exports.summarizeMatchedRelativeStudy;
const base = { signalId: "signal-1", stockCode: "3762", aiPowerAtSignal: 95, benchmark: "nikkei", window: "daily_close", horizonTradingDays: 1, fromDate: "2026-10-20", toDate: "2026-10-21", excessReturnPoints: 4 };
const result = summarize([base, { ...base, signalId: "signal-2", excessReturnPoints: 6 }, { ...base, signalId: "signal-3", benchmark: "topix" }, { ...base, signalId: "signal-4", horizonTradingDays: 5 }, { ...base, signalId: "signal-5", aiPowerAtSignal: 10 }, base]);
assert.equal(result.accepted, 5);
assert.equal(result.rejected, 1);
assert.equal(result.groups.length, 4);
assert.equal(result.groups[0].sampleSize, 2);
assert.equal(result.groups[0].meanExcessReturnPoints, 5);
assert.equal(result.groups[0].medianExcessReturnPoints, 5);
assert.equal(result.groups[0].outperformRatePct, 100);
assert.equal(summarize([{ ...base, horizonTradingDays: 0 }]).rejected, 1);
assert.equal(summarize([{ ...base, excessReturnPoints: Number.NaN }]).rejected, 1);
console.log("PASS: 9 matched market-relative cohort checks");
