import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import ts from "typescript";
import vm from "node:vm";
const src = readFileSync(new URL("../app/lib/research/marketRelativePerformance.ts", import.meta.url), "utf8");
const js = ts.transpileModule(src, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
const module = { exports: {} };
vm.runInNewContext(js, { module, exports: module.exports, Number, String });
const calculate = module.exports.calculateMarketRelativePerformance;
const stock = { status: "comparable", stockCode: "3762", window: "daily_close", fromDate: "2026-10-20", toDate: "2026-10-21", changePct: 3 };
const market = { status: "comparable", index: "nikkei", window: "daily_close", fromDate: "2026-10-20", toDate: "2026-10-21", changePct: -2 };
assert.equal(calculate(stock, market).status, "comparable");
assert.equal(calculate(stock, market).excessReturnPoints, 5);
assert.equal(calculate(stock, market).relativeStrength, "outperformed");
assert.equal(calculate({ ...stock, changePct: -4 }, market).relativeStrength, "underperformed");
assert.equal(calculate({ ...stock, changePct: -2 }, market).relativeStrength, "matched");
assert.equal(calculate(stock, { ...market, toDate: "2026-10-22" }).status, "incompatible");
assert.equal(calculate(stock, { ...market, window: "intraday_0905" }).status, "incompatible");
assert.equal(calculate({ ...stock, stockCode: "bad" }, market).status, "invalid");
assert.equal(calculate(stock, { ...market, changePct: Number.NaN }).status, "invalid");
console.log("PASS: 9 market-relative performance checks");
