-- Web Push preferences and one-shot user-set price thresholds.
-- Never expose these tables through the browser Data API.
CREATE TABLE IF NOT EXISTS public.push_notification_preferences (
  user_email text PRIMARY KEY,
  preferences jsonb NOT NULL DEFAULT '{}'::jsonb,
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT push_preferences_object CHECK (jsonb_typeof(preferences) = 'object')
);
ALTER TABLE public.push_notification_preferences ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.push_notification_preferences FROM anon, authenticated;

CREATE TABLE IF NOT EXISTS public.push_price_targets (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_email text NOT NULL,
  code text NOT NULL CHECK (code ~ '^[0-9A-Z]{4}$'),
  direction text NOT NULL CHECK (direction IN ('ABOVE', 'BELOW')),
  threshold numeric(14,2) NOT NULL CHECK (threshold > 0 AND threshold <= 1000000000),
  claimed_at timestamptz,
  notified_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (user_email, code, direction, threshold)
);
CREATE INDEX IF NOT EXISTS push_price_targets_pending_idx
  ON public.push_price_targets (user_email, id) WHERE notified_at IS NULL;
ALTER TABLE public.push_price_targets ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.push_price_targets FROM anon, authenticated;
REVOKE ALL ON SEQUENCE public.push_price_targets_id_seq FROM anon, authenticated;
