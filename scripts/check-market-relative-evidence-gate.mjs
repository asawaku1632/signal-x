import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import ts from "typescript";
import vm from "node:vm";
const src = readFileSync(new URL("../app/lib/research/marketRelativeEvidenceGate.ts", import.meta.url), "utf8");
const js = ts.transpileModule(src, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
const module = { exports: {} };
vm.runInNewContext(js, { module, exports: module.exports, Date, Number, String });
const validate = module.exports.validateHistoricalEvidence;
const row = { signalId: "s1", stockCode: "3762", frozenAiPower: 95, signalObservedAt: "2026-10-20T00:00:00Z", entryPrice: 100, exitPrice: 110, entryObservedAt: "2026-10-20T00:05:00Z", exitObservedAt: "2026-10-21T00:05:00Z", benchmark: "nikkei", benchmarkEntryPrice: 40000, benchmarkExitPrice: 40100, benchmarkEntryObservedAt: "2026-10-20T00:05:00Z", benchmarkExitObservedAt: "2026-10-21T00:05:00Z" };
assert.equal(validate(row).status, "eligible");
assert.ok(validate({ ...row, frozenAiPower: null }).reasons.includes("missing_frozen_ai_power"));
assert.ok(validate({ ...row, signalObservedAt: null }).reasons.includes("missing_signal_timestamp"));
assert.ok(validate({ ...row, entryPrice: null }).reasons.includes("missing_stock_prices"));
assert.ok(validate({ ...row, benchmarkExitPrice: null }).reasons.includes("missing_benchmark_prices"));
assert.ok(validate({ ...row, entryObservedAt: "2026-10-19T00:05:00Z" }).reasons.includes("entry_precedes_signal"));
assert.ok(validate({ ...row, exitObservedAt: row.entryObservedAt }).reasons.includes("invalid_stock_horizon"));
assert.ok(validate({ ...row, benchmarkEntryObservedAt: "2026-10-20T00:06:00Z" }).reasons.includes("entry_timestamp_mismatch"));
assert.ok(validate({ ...row, benchmarkExitObservedAt: null }).reasons.includes("missing_benchmark_timestamps"));
console.log("PASS: 9 historical evidence gate checks");
