import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import ts from "typescript";
import vm from "node:vm";
const src = readFileSync(new URL("../app/lib/research/marketRelativePowerCohorts.ts", import.meta.url), "utf8");
const js = ts.transpileModule(src, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
const module = { exports: {} };
vm.runInNewContext(js, { module, exports: module.exports, Date, Number, String, Map, Set });
const { powerCohort, summarizePowerCohorts } = module.exports;
const base = { stockCode: "3762", aiPowerAtSignal: 93, signalAt: "2026-10-20T06:00:00Z", fromDate: "2026-10-20", toDate: "2026-10-21", benchmark: "nikkei", window: "daily_close", excessReturnPoints: 5 };
assert.equal(powerCohort(90), "high_90_plus");
assert.equal(powerCohort(39), "low_under_40");
assert.equal(powerCohort(40), "middle_40_to_89");
assert.equal(powerCohort(101), null);
const result = summarizePowerCohorts([base, { ...base, stockCode: "9684", aiPowerAtSignal: 20, excessReturnPoints: -3 }, base]);
assert.equal(result.accepted, 2);
assert.equal(result.rejected, 1);
assert.equal(result.summary[0].meanExcessReturnPoints, 5);
assert.equal(result.summary[0].outperformRatePct, 100);
assert.equal(result.summary[2].outperformRatePct, 0);
console.log("PASS: 9 frozen AI POWER cohort checks");
