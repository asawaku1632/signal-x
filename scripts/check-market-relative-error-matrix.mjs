import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import ts from "typescript";
import vm from "node:vm";
const src = readFileSync(new URL("../app/lib/research/marketRelativeErrorMatrix.ts", import.meta.url), "utf8");
const js = ts.transpileModule(src, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
const module = { exports: {} };
vm.runInNewContext(js, { module, exports: module.exports, Date, Number, String, Set, Math });
const summarize = module.exports.summarizeRatingSurprises;
const base = { stockCode: "3762", aiPowerAtSignal: 20, signalAt: "2026-10-20T06:00:00Z", fromDate: "2026-10-20", toDate: "2026-10-21", benchmark: "nikkei", window: "daily_close", stockReturnPct: 7, marketReturnPct: -1, excessReturnPoints: 8 };
const high = { ...base, stockCode: "9684", aiPowerAtSignal: 95, stockReturnPct: -8, marketReturnPct: -2, excessReturnPoints: -6 };
assert.equal(summarize([base, high]).status, "observed");
assert.equal(summarize([base, high]).lowScoreRallies.length, 1);
assert.equal(summarize([base, high]).highScoreFalls.length, 1);
assert.equal(summarize([base, base]).rejected, 1);
assert.equal(summarize([base]).highScoreFallRatePct, null);
assert.equal(summarize([{ ...high, stockReturnPct: 2, excessReturnPoints: 4 }]).highScoreFalls.length, 0);
assert.equal(summarize([{ ...base, aiPowerAtSignal: 60 }]).eligibleLow, 0);
assert.equal(summarize([{ ...base, excessReturnPoints: 2 }]).rejected, 1);
assert.equal(summarize([base], 0).status, "invalid_threshold");
console.log("PASS: 9 rating surprise matrix checks");
