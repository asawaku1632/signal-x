import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import ts from "typescript";
import vm from "node:vm";
const src = readFileSync(new URL("../app/lib/research/marketRelativeReversalStudy.ts", import.meta.url), "utf8");
const js = ts.transpileModule(src, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
const module = { exports: {} };
vm.runInNewContext(js, { module, exports: module.exports, Date, Number, String, Set, Math });
const study = module.exports.summarizeLowPowerReversals;
const row = { stockCode: "3762", aiPowerAtSignal: 20, signalAt: "2026-10-20T06:00:00Z", fromDate: "2026-10-20", toDate: "2026-10-21", benchmark: "nikkei", window: "daily_close", stockReturnPct: 7, marketReturnPct: -1, excessReturnPoints: 8 };
assert.equal(study([row]).status, "observed");
assert.equal(study([row]).matchedCount, 1);
assert.equal(study([row, row]).rejected, 1);
assert.equal(study([{ ...row, aiPowerAtSignal: 90 }]).matchedCount, 0);
assert.equal(study([{ ...row, stockReturnPct: 3, excessReturnPoints: 4 }]).matchedCount, 0);
assert.equal(study([{ ...row, excessReturnPoints: 1 }]).rejected, 1);
assert.equal(study([{ ...row, toDate: "2026-10-19" }]).rejected, 1);
assert.equal(study([row], 0).status, "invalid_threshold");
assert.equal(study([]).matchedRatePct, null);
console.log("PASS: 9 low-score reversal retrospective checks");
