import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import ts from "typescript";
import vm from "node:vm";
const src = readFileSync(new URL("../app/lib/research/aiRatingReversalStudy.ts", import.meta.url), "utf8");
const js = ts.transpileModule(src, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
const module = { exports: {} };
vm.runInNewContext(js, { module, exports: module.exports, Date, Number, String });
const evalReversal = module.exports.evaluateRatingReversal;
const frozen = { stockCode: "3762", aiPower: 30, frozenAt: "2026-10-20T06:00:00Z", sessionDateJst: "2026-10-20", referencePrice: 1000 };
const forward = { stockCode: "3762", sessionDateJst: "2026-10-21", observedPrice: 1050, observedAt: "2026-10-21T06:00:00Z" };
assert.equal(evalReversal(frozen, forward).category, "low_score_rally");
assert.equal(evalReversal(frozen, forward).retrospectiveOnly, true);
assert.equal(evalReversal({ ...frozen, aiPower: 90 }, { ...forward, observedPrice: 950 }).category, "high_score_decline");
assert.equal(evalReversal({ ...frozen, aiPower: 60 }, forward).category, "other");
assert.equal(evalReversal(frozen, { ...forward, stockCode: "9984" }).status, "invalid");
assert.equal(evalReversal(frozen, { ...forward, sessionDateJst: "2026-10-20" }).status, "not_forward");
assert.equal(evalReversal(frozen, { ...forward, observedAt: "2026-10-19T06:00:00Z" }).status, "invalid_timestamp");
assert.equal(evalReversal({ ...frozen, aiPower: 101 }, forward).status, "invalid");
assert.equal(evalReversal(frozen, { ...forward, observedPrice: 0 }).status, "invalid");
console.log("PASS: 9 AI rating reversal study checks");
