import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import ts from "typescript";
import vm from "node:vm";
const src = readFileSync(new URL("../app/lib/research/marketIndexBenchmarkPair.ts", import.meta.url), "utf8");
const js = ts.transpileModule(src, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
const module = { exports: {} };
vm.runInNewContext(js, { module, exports: module.exports, Date, Number, String });
const compare = module.exports.compareBenchmarkPoints;
const before = { index: "nikkei", window: "daily_close", sessionDateJst: "2026-10-20", value: 40000, source: "synthetic" };
const after = { ...before, sessionDateJst: "2026-10-21", value: 40400 };
assert.equal(compare(before, after).status, "comparable");
assert.equal(compare(before, after).changePct, 1);
assert.equal(compare(before, { ...after, index: "topix" }).status, "incompatible");
assert.equal(compare(before, { ...after, window: "intraday_0905" }).status, "incompatible");
assert.equal(compare(before, { ...after, sessionDateJst: "2026-10-19" }).status, "invalid_date");
assert.equal(compare(before, { ...after, value: 0 }).status, "invalid");
assert.equal(compare(before, { ...after, sessionDateJst: "2026-10-20" }).status, "same_session");
const intradayBefore = { ...before, window: "intraday_0905", observedAt: "2026-10-20T00:05:00Z" };
assert.equal(compare(intradayBefore, { ...after, window: "intraday_0905" }).status, "missing_timestamp");
assert.equal(compare(intradayBefore, { ...after, window: "intraday_0905", observedAt: "2026-10-21T00:05:00Z" }).status, "comparable");
console.log("PASS: 9 market-index benchmark pair checks");
